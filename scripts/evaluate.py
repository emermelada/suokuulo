"""Run every clip in test_clips/<label>/ through BirdNET + the smoother and
write eval_results.md and eval_results.csv.

A clip is a hit if its label is confirmed at least once (2 hits in 3 windows,
section 7). Each clip gets a fresh smoother and a simulated clock, so results
do not depend on clip order or wall time. Folders that are not a species id
(e.g. background/) are negatives: any confirmed disturbance is a false alarm.

Usage: python scripts/evaluate.py [--config config/laptop.yaml]
"""
import argparse
import csv
import sys
import time
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from suokuulo import config  # noqa: E402
from suokuulo.audio import FileSource  # noqa: E402
from suokuulo.classifier import BirdNetClassifier  # noqa: E402
from suokuulo.detection import Smoother  # noqa: E402
from suokuulo.pipeline import simulated  # noqa: E402


def run_clip(path, classifier, cfg, timings):
    """Return (windows, set of confirmed labels, per-label count of hit windows)."""
    windows, now = simulated(FileSource(path).windows())
    smoother = Smoother(cfg, now)
    confirmed, hit_windows, n = set(), defaultdict(int), 0
    for w in windows:
        t0 = time.perf_counter()
        detections = classifier.classify(w, 48000)
        timings.append(time.perf_counter() - t0)
        confirmed |= {e.label for e in smoother.update(detections)}
        for d in smoother.hits:
            hit_windows[d.label] += 1
        n += 1
    return n, confirmed, hit_windows


def source(path):
    name = Path(path).name
    return "ESC-50" if name.startswith("ESC50") else "frugalai" if name.startswith("FRUGALAI") else "xeno-canto"


def pct(a, b):
    return f"{100 * a / b:.0f}%" if b else "-"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="config/laptop.yaml")
    ap.add_argument("--clips", default="test_clips")
    args = ap.parse_args()
    cfg = config.load(args.config)
    species = config.load_species(cfg.species_file)
    kind = {s.id: s.kind for s in species}
    classifier = BirdNetClassifier(species, cfg.min_conf)

    timings, rows = [], []
    for folder in sorted(p for p in Path(args.clips).iterdir() if p.is_dir()):
        for f in FileSource(folder).files:
            n, confirmed, hit_windows = run_clip(f, classifier, cfg, timings)
            rows.append({"file": str(f), "label": folder.name, "windows": n,
                         "confirmed": ";".join(sorted(confirmed)),
                         "target_hit_windows": hit_windows.get(folder.name, 0),
                         "disturbance_hit_windows": sum(v for k, v in hit_windows.items() if kind[k] == "disturbance")})
        print(f"{folder.name:15s} done")

    with open("eval_results.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    by_label = defaultdict(list)
    for r in rows:
        by_label[r["label"], source(r["file"])].append(r)
    pos = ["| label | source | clips | hits | misses | hit rate | window hit rate | any-disturbance window rate |",
           "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    neg = ["| folder | source | clips | windows | clips with disturbance alarm | clips with indicator confirmed | disturbance window false-hit rate |",
           "| --- | --- | --- | --- | --- | --- | --- |"]
    for (label, src), rs in by_label.items():
        windows = sum(r["windows"] for r in rs)
        if label in kind:
            hits = sum(label in r["confirmed"].split(";") for r in rs)
            target_windows = sum(r["target_hit_windows"] for r in rs)
            dist_windows = sum(r["disturbance_hit_windows"] for r in rs)
            pos.append(f"| {label} | {src} | {len(rs)} | {hits} | {len(rs) - hits} | {pct(hits, len(rs))} "
                       f"| {pct(target_windows, windows)} | {pct(dist_windows, windows)} |")
        else:
            confirmed = [set(filter(None, r["confirmed"].split(";"))) for r in rs]
            alarms = sum(any(kind[l] == "disturbance" for l in c) for c in confirmed)
            birds = sum(any(kind[l] == "indicator" for l in c) for c in confirmed)
            dist_windows = sum(r["disturbance_hit_windows"] for r in rs)
            neg.append(f"| {label} | {src} | {len(rs)} | {windows} | {alarms} | {birds} | {pct(dist_windows, windows)} |")

    mean_ms = 1000 * sum(timings) / len(timings)
    report = f"""# SuoKuulo evaluation

Generated by `python scripts/evaluate.py` on {time.strftime('%Y-%m-%d %H:%M')}.
BirdNET v2.4 TFLite model (files from birdnetlib), run directly with ai-edge-litert. Thresholds: indicator
{cfg.indicator_hit}, disturbance {cfg.disturbance_hit}, confirm {cfg.hits_needed} of {cfg.hit_window} windows.

- Model imports + load: {classifier.load_s:.2f} s
- Mean inference: {mean_ms:.0f} ms per 3 s window over {len(timings)} windows (this machine)

## Positives

A clip is a hit if its label is confirmed at least once. Window hit rate is the
share of all 3 s windows where the label scored at or above its threshold.
Any-disturbance window rate counts windows where any disturbance label hit
(an engine hit on a chainsaw clip still raises the alarm).

{chr(10).join(pos)}

## Negatives (false alarms)

{chr(10).join(neg)}

## Caveats

- Clips of 3 s or less (rfcx/frugalai) are a single window, so they can never
  reach 2 hits in 3 windows. For them only the window hit rate is meaningful.
- ESC-50 clips are 5 s: two windows, the second one 2 s of audio plus padding.
- Xeno-canto clips are mostly short, focal recordings; a field microphone on a
  bog will hear birds further away and quieter.
- Per-clip detail: eval_results.csv.
"""
    Path("eval_results.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
